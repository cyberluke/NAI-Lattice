//! End-to-end R01 / NAIOS-001 activation on an ISOLATED host instance.
//!
//! The test starts its own monitor/worker from a scratch `NAI_LATTICE_ROOT`,
//! with a unique `NAI_LATTICE_INSTANCE` and a free control port. It never talks
//! to the production singleton, never writes the production `active.json`, and
//! stops/cleans its own tree before returning.
//!
//! The staged candidate is a copy of the SAME 0.1.3 bytes (a mechanism test, not
//! a real 0.1.4 build). Identity is therefore asserted through the endpoint pid
//! and the serving process image path, never through the claimed version. The
//! compiled `runtime.describe.host_version` remains 0.1.3 and that is expected.
#![cfg(windows)]

use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

use nai_lattice_client::win_pipe::NamedPipeStream;
use nai_lattice_client::NafClient;
use nai_lattice_protocol::pb;
use serde_json::{json, Value};
use sha2::{Digest, Sha256};

const INSTANCE_MAX: usize = 24;
const OP_TIMEOUT: Duration = Duration::from_secs(45);
const START_TIMEOUT: Duration = Duration::from_secs(40);

fn now_ms() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis() as i64
}

fn random_hex(bytes: usize) -> String {
    let mut buf = vec![0u8; bytes];
    // getrandom is already in the dependency graph through uuid/tokio; use the
    // OS generator via std's process/time entropy only for a test-unique label.
    // (This value is not a credential; the control token is generated by the
    // host with UUID v4.)
    let seed = format!("{}:{}:{}", std::process::id(), now_ms(), std::thread::current().name().unwrap_or("t"));
    let hash = blake3::hash(seed.as_bytes()).to_hex().to_string();
    for (index, byte) in buf.iter_mut().enumerate() {
        *byte = u8::from_str_radix(&hash[(index * 2) % hash.len()..(index * 2) % hash.len() + 2], 16)
            .unwrap_or(0);
    }
    buf.iter().map(|b| format!("{b:02x}")).collect()
}

fn unique_instance() -> String {
    let mut name = format!("act-{}-{}", std::process::id(), &random_hex(4));
    if name.len() > INSTANCE_MAX {
        name.truncate(INSTANCE_MAX);
    }
    name
}

fn free_port() -> u16 {
    let listener = std::net::TcpListener::bind(("127.0.0.1", 0)).expect("bind ephemeral port");
    let port = listener.local_addr().expect("local addr").port();
    drop(listener);
    port
}

fn sha256_file(path: &Path) -> String {
    let mut file = std::fs::File::open(path).expect("open exe for hash");
    let mut hasher = Sha256::new();
    let mut buf = [0u8; 64 * 1024];
    loop {
        use std::io::Read as _;
        let n = file.read(&mut buf).expect("read exe for hash");
        if n == 0 {
            break;
        }
        hasher.update(&buf[..n]);
    }
    format!("{:x}", hasher.finalize())
}

fn write_atomic(path: &Path, bytes: &[u8]) {
    let parent = path.parent().expect("parent");
    std::fs::create_dir_all(parent).expect("create parent");
    let tmp = parent.join(format!(
        ".{}.tmp-{}",
        path.file_name().unwrap().to_string_lossy(),
        std::process::id()
    ));
    {
        let mut file = std::fs::File::create(&tmp).expect("create tmp");
        file.write_all(bytes).expect("write tmp");
        file.sync_all().expect("sync tmp");
    }
    std::fs::rename(&tmp, path).expect("rename tmp");
}

fn read_json(path: &Path) -> Option<Value> {
    std::fs::read(path)
        .ok()
        .and_then(|b| serde_json::from_slice(&b).ok())
}

fn wait_for<T>(timeout: Duration, mut probe: impl FnMut() -> Option<T>) -> Option<T> {
    let started = Instant::now();
    loop {
        if let Some(value) = probe() {
            return Some(value);
        }
        if started.elapsed() >= timeout {
            return None;
        }
        std::thread::sleep(Duration::from_millis(50));
    }
}

fn process_alive(pid: u32) -> bool {
    use windows::Win32::Foundation::CloseHandle;
    use windows::Win32::System::Threading::{
        GetExitCodeProcess, OpenProcess, PROCESS_QUERY_LIMITED_INFORMATION,
    };
    const STILL_ACTIVE: u32 = 259;
    unsafe {
        let Ok(handle) = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, false, pid) else {
            return false;
        };
        let mut code = 0u32;
        let ok = GetExitCodeProcess(handle, &mut code).is_ok();
        let _ = CloseHandle(handle);
        ok && code == STILL_ACTIVE
    }
}

fn process_image(pid: u32) -> Option<PathBuf> {
    use windows::Win32::Foundation::CloseHandle;
    use windows::Win32::System::Threading::{
        OpenProcess, QueryFullProcessImageNameW, PROCESS_NAME_WIN32,
        PROCESS_QUERY_LIMITED_INFORMATION,
    };
    unsafe {
        let handle = OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION, false, pid).ok()?;
        let mut buffer = vec![0u16; 4096];
        let mut len = buffer.len() as u32;
        let ok = QueryFullProcessImageNameW(
            handle,
            PROCESS_NAME_WIN32,
            windows::core::PWSTR(buffer.as_mut_ptr()),
            &mut len,
        )
        .is_ok();
        let _ = CloseHandle(handle);
        if !ok {
            return None;
        }
        Some(PathBuf::from(String::from_utf16_lossy(
            &buffer[..len as usize],
        )))
    }
}

fn paths_equal(a: &Path, b: &Path) -> bool {
    let a = std::fs::canonicalize(a).unwrap_or_else(|_| a.to_path_buf());
    let b = std::fs::canonicalize(b).unwrap_or_else(|_| b.to_path_buf());
    a.to_string_lossy().eq_ignore_ascii_case(&b.to_string_lossy())
}

struct Endpoint {
    pid: u32,
    canonical_pipe: String,
    instance_id: String,
}

fn read_endpoint(root: &Path) -> Option<Endpoint> {
    let value = read_json(&root.join("endpoint.json"))?;
    Some(Endpoint {
        pid: value.get("pid")?.as_u64()? as u32,
        canonical_pipe: value.get("canonical_pipe")?.as_str()?.to_string(),
        instance_id: value.get("instance_id")?.as_str()?.to_string(),
    })
}

fn endpoint_ready(root: &Path, expected_instance: &str) -> Option<Endpoint> {
    let endpoint = read_endpoint(root)?;
    if !process_alive(endpoint.pid) {
        return None;
    }
    let value = read_json(&root.join("endpoint.json"))?;
    if value.get("instance").and_then(Value::as_str) != Some(expected_instance) {
        return None;
    }
    Some(endpoint)
}

fn probe(pipe: &str) -> Result<(String, Value), String> {
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .map_err(|e| e.to_string())?;
    runtime.block_on(async move {
        let stream = NamedPipeStream::connect(pipe).map_err(|e| e.to_string())?;
        let handshake = pb::HandshakeRequest {
            client_app_id: "activation-e2e".into(),
            client_version: "0.1.0".into(),
            client_pid: std::process::id() as i64,
            naf_min: 1,
            naf_max: 1,
            requested_capabilities: vec![
                "runtime.health".into(),
                "runtime.describe".into(),
                "runtime.shutdown_if_idle".into(),
            ],
            package_identity: "activation-e2e".into(),
            build_sha: "e2e".into(),
            nonce: b"activation-e2e".to_vec(),
        };
        let mut client = NafClient::connect(stream, handshake)
            .await
            .map_err(|e| e.to_string())?;
        let body = client
            .dispatch("runtime.health", b"{}", None)
            .await
            .map_err(|e| e.to_string())?;
        let health: Value = serde_json::from_slice(&body).map_err(|e| e.to_string())?;
        let body = client
            .dispatch("runtime.describe", b"{}", None)
            .await
            .map_err(|e| e.to_string())?;
        let describe: Value = serde_json::from_slice(&body).map_err(|e| e.to_string())?;
        Ok((client.runtime_instance_id.clone(), {
            let mut combined = health;
            combined["describe"] = describe;
            combined
        }))
    })
}

fn shutdown(pipe: &str) -> Result<(), String> {
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .map_err(|e| e.to_string())?;
    runtime.block_on(async move {
        let stream = NamedPipeStream::connect(pipe).map_err(|e| e.to_string())?;
        let handshake = pb::HandshakeRequest {
            client_app_id: "activation-e2e".into(),
            client_version: "0.1.0".into(),
            client_pid: std::process::id() as i64,
            naf_min: 1,
            naf_max: 1,
            requested_capabilities: vec![
                "runtime.health".into(),
                "runtime.shutdown_if_idle".into(),
            ],
            package_identity: "activation-e2e".into(),
            build_sha: "e2e".into(),
            nonce: b"activation-e2e".to_vec(),
        };
        let mut client = NafClient::connect(stream, handshake)
            .await
            .map_err(|e| e.to_string())?;
        client
            .dispatch("runtime.shutdown_if_idle", b"{}", None)
            .await
            .map(|_| ())
            .map_err(|e| e.to_string())
    })
}

struct Candidate {
    dir: PathBuf,
    exe: PathBuf,
    hash: String,
}

fn stage_candidate(dir: &Path, source: &Path, signature_status: &str) -> Candidate {
    std::fs::create_dir_all(dir).expect("create staged dir");
    let exe = dir.join("nai-fabric-host.exe");
    std::fs::copy(source, &exe).expect("copy candidate");
    let hash = sha256_file(&exe);
    let manifest = json!({
        "version": dir.file_name().unwrap().to_string_lossy(),
        "protocol_min": 1,
        "protocol_max": 1,
        "target": "x86_64-pc-windows-msvc",
        "sha256": hash,
        "built_at_unix_ms": now_ms(),
        "source": "NAI-Lattice",
        "git": "e2e",
        "signature_status": signature_status,
    });
    write_atomic(&dir.join("host-manifest.json"), manifest.to_string().as_bytes());
    Candidate {
        dir: dir.to_path_buf(),
        exe,
        hash,
    }
}

fn write_request(
    base: &Path,
    operation_id: &str,
    candidate: &Candidate,
    version: &str,
    token: &str,
    allow_unsigned: bool,
) {
    let request = json!({
        "schema": 1,
        "operation_id": operation_id,
        "staged_dir": candidate.dir.to_string_lossy(),
        "target_version": version,
        "exe_sha256": candidate.hash,
        "protocol_min": 1,
        "protocol_max": 1,
        "storage_schema": 1,
        "authorization": token,
        "allow_unsigned": allow_unsigned,
        "requested_at_unix_ms": now_ms(),
    });
    write_atomic(
        &base.join("activation.request.json"),
        request.to_string().as_bytes(),
    );
}

fn wait_status(base: &Path, operation_id: &str) -> Value {
    let status = wait_for(OP_TIMEOUT, || {
        let status = read_json(&base.join("activation.status.json"))?;
        if status.get("operation_id").and_then(Value::as_str) != Some(operation_id) {
            return None;
        }
        let phase = status.get("phase").and_then(Value::as_str).unwrap_or("");
        if matches!(phase, "committed" | "rolled_back" | "failed" | "busy") {
            Some(status)
        } else {
            None
        }
    })
    .unwrap_or_else(|| {
        let current = std::fs::read_to_string(base.join("activation.status.json"))
            .unwrap_or_else(|_| "<no status file>".into());
        panic!("activation {operation_id} did not reach a terminal phase; status={current}");
    });
    eprintln!(
        "activation status {}: {}",
        operation_id,
        serde_json::to_string_pretty(&status).unwrap_or_default()
    );
    status
}

fn stop_process(pid: u32) {
    if !process_alive(pid) {
        return;
    }
    use windows::Win32::Foundation::CloseHandle;
    use windows::Win32::System::Threading::{
        OpenProcess, TerminateProcess, PROCESS_QUERY_LIMITED_INFORMATION, PROCESS_TERMINATE,
    };
    unsafe {
        if let Ok(handle) = OpenProcess(
            PROCESS_QUERY_LIMITED_INFORMATION | PROCESS_TERMINATE,
            false,
            pid,
        ) {
            let _ = TerminateProcess(handle, 1);
            let _ = CloseHandle(handle);
        }
    }
}

/// Kills the isolated monitor on any panic, which also closes its Windows Job
/// Object and reaps the worker. Without this guard a failed assertion would
/// leave a stray host running and the test harness would wait on its handles.
struct ManagedMonitor {
    child: Option<Child>,
    worker_pid: Arc<Mutex<Option<u32>>>,
}

impl ManagedMonitor {
    fn new(child: Child) -> Self {
        Self {
            child: Some(child),
            worker_pid: Arc::new(Mutex::new(None)),
        }
    }

    fn set_worker(&self, pid: u32) {
        *self.worker_pid.lock().unwrap() = Some(pid);
    }

    fn wait_exit(&mut self, timeout: Duration) -> bool {
        let waited = wait_for(timeout, || {
            self.child
                .as_mut()
                .and_then(|child| child.try_wait().ok().flatten())
        });
        if waited.is_some() {
            self.child = None;
            return true;
        }
        false
    }

    fn stop(&mut self) {
        if let Some(mut child) = self.child.take() {
            let _ = child.kill();
            let _ = child.wait();
        }
        if let Some(pid) = *self.worker_pid.lock().unwrap() {
            stop_process(pid);
        }
    }
}

impl Drop for ManagedMonitor {
    fn drop(&mut self) {
        self.stop();
    }
}


#[test]
fn activation_commit_and_rollback_on_isolated_instance() {
    // A plain scratch directory (not TempDir) so a failed assertion leaves the
    // evidence on disk for diagnosis. The success path removes it explicitly.
    let temp = std::env::temp_dir().join(format!(
        "nai-act-e2e-{}-{}",
        std::process::id(),
        random_hex(3)
    ));
    let _ = std::fs::remove_dir_all(&temp);
    let base = temp.join("Lattice");
    let root = base.join("v1");
    let runtime = base.join("runtime");
    std::fs::create_dir_all(&runtime).expect("runtime dir");
    std::fs::create_dir_all(&root).expect("runtime root");
    eprintln!("scratch base={}", base.display());

    let host_exe = PathBuf::from(env!("CARGO_BIN_EXE_nai-fabric-host"));
    assert!(host_exe.is_file(), "test host binary missing: {}", host_exe.display());

    // The current worker is a copy of the test build under a 0.1.3 label.
    let old = stage_candidate(&runtime.join("0.1.3-qa"), &host_exe, "NotSigned");
    let instance = unique_instance();
    let port = free_port();
    let mut monitor = ManagedMonitor::new(
        Command::new(&old.exe)
            .env("NAI_LATTICE_ROOT", &root)
            .env("NAI_LATTICE_INSTANCE", &instance)
            .env("HELLDESK_CTRL_PORT", port.to_string())
            .stdin(Stdio::null())
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .spawn()
            .expect("start isolated monitor"),
    );

    let first = wait_for(START_TIMEOUT, || endpoint_ready(&root, &instance)).unwrap_or_else(|| {
        panic!(
            "isolated host never published a live endpoint; instance={instance} root={}",
            root.display()
        )
    });
    monitor.set_worker(first.pid);
    let (first_instance, first_health) = probe(&first.canonical_pipe).expect("first probe");
    assert_eq!(first_instance, first.instance_id);
    assert_eq!(first_health["state"], "healthy");
    assert_eq!(
        process_image(first.pid).map(|p| paths_equal(&p, &old.exe)).unwrap_or(false),
        true,
        "initial endpoint must serve the staged 0.1.3 copy"
    );
    eprintln!(
        "phase0 endpoint pid={} pipe={} instance_id={}",
        first.pid, first.canonical_pipe, first.instance_id
    );

    let token = wait_for(Duration::from_secs(10), || {
        std::fs::read_to_string(base.join("control.token"))
            .ok()
            .map(|s| s.trim().to_string())
            .filter(|s| !s.is_empty())
    })
    .expect("host must create <base>/control.token");

    // ── 1. successful activation of a copy of the same bytes ────────────────
    let candidate = stage_candidate(&runtime.join("0.1.4-qa"), &old.exe, "NotSigned");
    let op1 = format!("act-{}-{}", now_ms(), &random_hex(4));
    write_request(&base, &op1, &candidate, "0.1.4-qa", &token, true);
    let status1 = wait_status(&base, &op1);
    assert_eq!(status1["phase"], "committed", "status1={status1}");
    assert_eq!(status1["to_version"], "0.1.4-qa");

    let second = wait_for(Duration::from_secs(10), || {
        let endpoint = read_endpoint(&root)?;
        if endpoint.pid == first.pid || !process_alive(endpoint.pid) {
            return None;
        }
        Some(endpoint)
    })
    .expect("new endpoint after commit");
    monitor.set_worker(second.pid);
    assert_ne!(second.pid, first.pid, "a new serving pid is required");
    assert!(
        process_image(second.pid)
            .map(|p| paths_equal(&p, &candidate.exe))
            .unwrap_or(false),
        "committed endpoint must serve the staged 0.1.4-qa candidate"
    );
    let (second_instance, second_health) = probe(&second.canonical_pipe).expect("second probe");
    assert_eq!(second_instance, second.instance_id);
    assert_eq!(second_health["state"], "healthy");
    assert_eq!(
        status1["endpoint"]["pid"].as_u64().map(|p| p as u32),
        Some(second.pid),
        "committed status must carry the verified endpoint pid"
    );
    let active1 = read_json(&base.join("active.json")).expect("active.json after commit");
    eprintln!(
        "active.json raw: {}",
        std::fs::read_to_string(base.join("active.json")).unwrap_or_default()
    );
    assert_eq!(active1["version"], "0.1.4-qa");
    assert_eq!(active1["sha256"], candidate.hash);
    assert!(
        active1["path"]
            .as_str()
            .map(|p| paths_equal(Path::new(p), &candidate.exe))
            .unwrap_or(false),
        "active.json path must name the staged candidate: {active1}"
    );
    assert!(
        !base.join("activation.journal.json").exists(),
        "journal must be removed after commit"
    );
    eprintln!(
        "phase1 committed pid={} image={} active_version={} journal=absent",
        second.pid,
        process_image(second.pid)
            .map(|p| p.display().to_string())
            .unwrap_or_default(),
        active1["version"]
    );

    // ── 2. broken candidate: spawn fails, old artifact rolls back ───────────
    let active_before = std::fs::read(base.join("active.json")).expect("read active before");
    let broken_dir = runtime.join("0.1.5-qa");
    std::fs::create_dir_all(&broken_dir).expect("broken dir");
    let broken_exe = broken_dir.join("nai-fabric-host.exe");
    std::fs::write(&broken_exe, b"this is not a PE executable\n").expect("write broken exe");
    let broken_hash = sha256_file(&broken_exe);
    write_atomic(
        &broken_dir.join("host-manifest.json"),
        json!({
            "version": "0.1.5-qa",
            "protocol_min": 1,
            "protocol_max": 1,
            "target": "x86_64-pc-windows-msvc",
            "sha256": broken_hash,
            "source": "NAI-Lattice",
            "git": "e2e",
            "signature_status": "NotSigned",
        })
        .to_string()
        .as_bytes(),
    );
    let broken = Candidate {
        dir: broken_dir,
        exe: broken_exe,
        hash: broken_hash,
    };
    let op2 = format!("act-{}-{}", now_ms(), &random_hex(4));
    write_request(&base, &op2, &broken, "0.1.5-qa", &token, true);
    let status2 = wait_status(&base, &op2);
    assert_eq!(status2["phase"], "rolled_back", "status2={status2}");
    let error2 = status2["error"].as_str().unwrap_or("");
    assert!(
        error2.contains("candidate spawn failed") || error2.contains("verified endpoint"),
        "rollback diagnostic must name the failure: {error2}"
    );
    assert_eq!(
        std::fs::read(base.join("active.json")).expect("read active after"),
        active_before,
        "active.json must be restored verbatim after rollback"
    );
    assert!(
        !base.join("activation.journal.json").exists(),
        "journal must be removed after rollback"
    );
    let third = wait_for(Duration::from_secs(15), || {
        let endpoint = read_endpoint(&root)?;
        if endpoint.pid == second.pid || !process_alive(endpoint.pid) {
            return None;
        }
        Some(endpoint)
    })
    .expect("rollback endpoint");
    monitor.set_worker(third.pid);
    assert_ne!(third.pid, second.pid, "rollback must start a new process");
    assert!(
        process_image(third.pid)
            .map(|p| paths_equal(&p, &candidate.exe))
            .unwrap_or(false),
        "rollback must serve the previous 0.1.4-qa artifact"
    );
    let (third_instance, third_health) = probe(&third.canonical_pipe).expect("third probe");
    assert_eq!(third_instance, third.instance_id);
    assert_eq!(third_health["state"], "healthy");
    let active2 = read_json(&base.join("active.json")).expect("active after rollback");
    assert_eq!(active2["version"], "0.1.4-qa");
    eprintln!(
        "phase2 rolled_back pid={} image={} active_version={} journal=absent error={}",
        third.pid,
        process_image(third.pid)
            .map(|p| p.display().to_string())
            .unwrap_or_default(),
        active2["version"],
        error2
    );

    // ── cleanup: cooperative stop, then hard-stop only our own tree ─────────
    let _ = shutdown(&third.canonical_pipe);
    let exited = monitor.wait_exit(Duration::from_secs(15));
    if !exited {
        eprintln!("monitor did not exit after cooperative stop; killing the isolated tree");
        monitor.stop();
    }
    // Best-effort wait for the worker to be gone, then remove the scratch root.
    let _ = wait_for(Duration::from_secs(5), || {
        if process_alive(third.pid) {
            None
        } else {
            Some(())
        }
    });
    let _ = std::fs::remove_dir_all(&temp);
}

    #[test]
    fn transitions_produce_snapshot_json_and_monotonic_since() {
        let controller = LifecycleController::new();
        assert_eq!(controller.state(), RuntimeState::Starting);

        let initial = controller.snapshot_json();
        assert_eq!(initial["state"], "starting");

        let transition = controller
            .set_state(RuntimeState::Healthy, None)
            .expect("starting -> healthy");
        assert_eq!(transition.from, RuntimeState::Starting);
        assert_eq!(transition.to, RuntimeState::Healthy);
        let healthy = controller.snapshot_json();
        assert_eq!(healthy["state"], "healthy");
        assert!(healthy["detail"].is_null());
        assert!(healthy["last_error"].is_null());
        assert!(
            healthy["since_unix_ms"].as_i64().unwrap()
                >= initial["since_unix_ms"].as_i64().unwrap()
        );

        std::thread::sleep(std::time::Duration::from_millis(5));
        let transition = controller
            .set_state(
                RuntimeState::Draining,
                Some("drain for update".to_string()),
            )
            .expect("healthy -> draining");
        assert_eq!(transition.from, RuntimeState::Healthy);
        assert_eq!(transition.detail.as_deref(), Some("drain for update"));
        let draining = controller.snapshot_json();
        assert_eq!(draining["state"], "draining");
        assert_eq!(draining["detail"], "drain for update");
        assert!(
            draining["since_unix_ms"].as_i64().unwrap()
                >= healthy["since_unix_ms"].as_i64().unwrap()
        );

        // Re-entering the current state updates detail without restarting since.
        assert!(controller
            .set_state(RuntimeState::Draining, Some("still draining".to_string()))
            .is_none());
        let same = controller.snapshot_json();
        assert_eq!(same["detail"], "still draining");
        assert_eq!(same["since_unix_ms"], draining["since_unix_ms"]);
        assert!(same["age_ms"].as_u64().is_some());

        controller.record_error("runtime.state event append failed");
        assert_eq!(
            controller.snapshot_json()["last_error"],
            "runtime.state event append failed"
        );
        controller.clear_error();
        assert!(controller.snapshot_json()["last_error"].is_null());
    }

    #[test]
    fn lock_acquire_refuses_competitors_and_requires_token() {
        let root = temp_root("lock");
        let lock = MaintenanceLock::new(&root);

        let acquired = lock.acquire("owner-a", "prune", 60_000).expect("acquire");
        let token = match &acquired {
            AcquireOutcome::Acquired {
                token,
                reclaimed,
                lock: record,
            } => {
                assert!(!reclaimed);
                assert_eq!(record.owner, "owner-a");
                token.clone()
            }
            other => panic!("expected acquire, got {other:?}"),
        };
        assert!(lock.path().exists());

        let second = lock.acquire("owner-b", "backup", 60_000).expect("acquire");
        match &second {
            AcquireOutcome::Refused(LockRefusal::Locked(holder)) => {
                assert_eq!(holder.owner, "owner-a");
                assert_eq!(holder.reason, "prune");
            }
            other => panic!("expected locked refusal, got {other:?}"),
        }
        let refusal = second.to_json();
        assert_eq!(refusal["ok"], false);
        assert_eq!(refusal["reason"], "locked");
        assert_eq!(refusal["holder"]["owner"], "owner-a");
        assert!(
            refusal["holder"].get("token").is_none(),
            "holder JSON must never expose the fencing token"
        );

        let status = lock.inspect().status_json(now_unix_ms());
        assert_eq!(status["locked"], true);
        assert_eq!(status["holder"]["owner"], "owner-a");
        assert!(status["holder"].get("token").is_none());
        assert!(status["expires_in_ms"].as_i64().unwrap() > 0);

        // Foreign release/extend are refused and leave the file untouched.
        let foreign_release = lock.release("not-the-token").expect("release");
        assert!(matches!(
            foreign_release,
            ReleaseOutcome::Refused(LockRefusal::NotOwner(_))
        ));
        assert_eq!(foreign_release.to_json()["reason"], "not_owner");
        assert!(lock.path().exists());

        let foreign_extend = lock.extend("not-the-token", 90_000).expect("extend");
        assert!(matches!(
            foreign_extend,
            ExtendOutcome::Refused(LockRefusal::NotOwner(_))
        ));
        assert!(lock.path().exists());

        // The exact token may extend, and the expiry advances.
        let extends_at = lock.inspect_at(now_unix_ms());
        let before_expiry = match extends_at {
            LockInspection::Live(record) => record.expires_at_unix_ms,
            other => panic!("expected live record, got {other:?}"),
        };
        let extended = lock.extend(&token, 90_000).expect("extend");
        let after_expiry = match &extended {
            ExtendOutcome::Extended(record) => {
                assert!(record.expires_at_unix_ms >= before_expiry);
                record.expires_at_unix_ms
            }
            other => panic!("expected extended, got {other:?}"),
        };
        assert!(after_expiry > before_expiry);

        // The exact token releases; the file disappears.
        let released = lock.release(&token).expect("release");
        assert!(matches!(released, ReleaseOutcome::Released(_)));
        assert!(!lock.path().exists());
        assert!(matches!(lock.inspect(), LockInspection::Absent));

        let _ = std::fs::remove_dir_all(&root);
    }

    #[test]
    fn expired_lock_is_reclaimed_with_reclaimed_flag() {
        let root = temp_root("reclaim");
        let lock = MaintenanceLock::new(&root);
        let now = now_unix_ms();

        // Acquire 10 s in the past with a 1 s TTL: already expired on disk.
        let dead = lock
            .acquire_at("dead-owner", "crashed", 1_000, now - 10_000)
            .expect("dead acquire");
        let dead_token = match dead {
            AcquireOutcome::Acquired { token, .. } => token,
            other => panic!("expected acquire, got {other:?}"),
        };
        assert!(matches!(lock.inspect(), LockInspection::Expired(_)));

        let takeover = lock
            .acquire_at("live-owner", "takeover", 60_000, now)
            .expect("reclaim");
        match takeover {
            AcquireOutcome::Acquired {
                token,
                reclaimed,
                lock: record,
            } => {
                assert!(reclaimed, "expired lock must be reclaimed");
                assert_ne!(token, dead_token);
                assert_eq!(record.owner, "live-owner");
            }
            other => panic!("expected reclaimed acquire, got {other:?}"),
        }
        assert!(matches!(lock.inspect(), LockInspection::Live(_)));

        let _ = std::fs::remove_dir_all(&root);
    }

    #[test]
    fn two_lock_instances_on_one_root_cannot_both_hold() {
        let root = temp_root("two");
        let first = MaintenanceLock::new(&root);
        let second = MaintenanceLock::new(&root);

        let acquired = first.acquire("first", "prune", 60_000).expect("acquire");
        let token = match &acquired {
            AcquireOutcome::Acquired { token, .. } => token.clone(),
            other => panic!("expected acquire, got {other:?}"),
        };
        assert!(acquired.is_acquired());
        assert!(!second
            .acquire("second", "backup", 60_000)
            .expect("acquire")
            .is_acquired());

        first.release(&token).expect("release");
        assert!(second
            .acquire("second", "backup", 60_000)
            .expect("acquire")
            .is_acquired());

        let _ = std::fs::remove_dir_all(&root);
    }

    #[test]
    fn concurrent_acquire_has_exactly_one_winner() {
        let root = temp_root("race");
        let mut handles = Vec::new();
        for index in 0..8 {
            let root = root.clone();
            handles.push(std::thread::spawn(move || {
                let lock = MaintenanceLock::new(&root);
                match lock
                    .acquire(&format!("thread-{index}"), "race", 60_000)
                    .expect("acquire")
                {
                    AcquireOutcome::Acquired { token, .. } => Some((token, lock)),
                    AcquireOutcome::Refused(_) => None,
                }
            }));
        }
        let winners: Vec<_> = handles
            .into_iter()
            .filter_map(|handle| handle.join().expect("thread"))
            .collect();
        assert_eq!(
            winners.len(),
            1,
            "exactly one contender may hold the lease"
        );
        let (token, lock) = winners.into_iter().next().expect("winner");
        assert!(matches!(
            lock.release(&token).expect("release"),
            ReleaseOutcome::Released(_)
        ));

        let _ = std::fs::remove_dir_all(&root);
    }

    #[test]
    fn unreadable_lock_is_never_stolen_or_deleted() {
        let root = temp_root("corrupt");
        let lock = MaintenanceLock::new(&root);
        std::fs::write(lock.path(), b"{ not a lock").expect("write corrupt lock");

        let acquired = lock.acquire("thief", "takeover", 60_000).expect("acquire");
        match acquired {
            AcquireOutcome::Refused(LockRefusal::Unreadable(_)) => {}
            other => panic!("expected unreadable refusal, got {other:?}"),
        }
        assert!(lock.path().exists());
        assert_eq!(
            std::fs::read(lock.path()).expect("lock content"),
            b"{ not a lock"
        );

        let released = lock.release("any-token").expect("release");
        match released {
            ReleaseOutcome::Refused(LockRefusal::Unreadable(_)) => {}
            other => panic!("expected unreadable refusal, got {other:?}"),
        }
        assert!(lock.path().exists());

        let _ = std::fs::remove_dir_all(&root);
    }

//! Runtime lifecycle state machine and cross-process maintenance lock (NAIOS-002).
//!
//! The runtime owns exactly one [`LifecycleController`]. It answers the cheap,
//! thread-safe question "what is this process doing right now?" and is the
//! source of `state` / `detail` / `last_error` / `since_unix_ms` in
//! `runtime.health`, `runtime.describe` provenance and the host's lifecycle
//! snapshot. State transitions are recorded by the runtime as durable-batched
//! `runtime.state` ledger events; this module deliberately does not depend on
//! the ledger so it stays usable from a shutdown path.
//!
//! # State machine
//!
//! ```text
//!   starting ──► healthy ──► draining ──► maintenance ──► healthy
//!       │           │            │              │
//!       └───────────┴────────────┴──────────────┴──► degraded
//! ```
//!
//! Any state may enter `degraded`; `degraded` is sticky until an explicit
//! transition. `maintenance` may also be *forced* by a live maintenance lock
//! even when the controller still says `healthy` (resolution happens in
//! `LatticeRuntime`: `degraded` wins over the lock; the lock wins over every
//! other controller state). The controller itself never guesses.
//!
//! # Maintenance lock
//!
//! Path: `<runtime root>/maintenance.lock.json` (the same `config.root` the
//! ledger uses, e.g. `%LOCALAPPDATA%\NAI\Lattice\v1`).
//!
//! ```json
//! {"schema":1,"owner":"nai-os","reason":"prune","token":"<64 hex>",
//!  "pid":1234,"acquired_at_unix_ms":1764000000000,
//!  "expires_at_unix_ms":1764000900000}
//! ```
//!
//! * Acquire creates the file with [`std::fs::OpenOptions::create_new`], so on
//!   one local filesystem exactly one contender wins. The token is generated by
//!   the lock and returned **only** to the acquirer; it is never included in
//!   holder JSON, `runtime.health` or `runtime.maintenance.status`.
//! * A live (unexpired) record refuses a foreign acquire with
//!   `{"ok":false,"reason":"locked","holder":{...}}`. That is a successful NAF
//!   call carrying a refusal, not a protocol error.
//! * Release and extend require the exact token. A release moves the file aside
//!   with an atomic rename and re-reads it before deleting anything: a stale
//!   token can never delete a lock it does not own. Extend refuses an expired
//!   record (an expired lease has already lost the right to renew).
//! * An expired record is reclaimed. Reclaim also renames the observed file to
//!   a unique staging name, then re-reads it. If the file changed between the
//!   observation and the rename (another actor reclaimed or extended it), the
//!   staged record is restored and the caller is refused rather than allowed to
//!   delete a lock it does not own.
//!
//! ## Exact reclaim race window
//!
//! No TTL file lock can be perfectly race-free without an OS handle lease. The
//! precise windows here are:
//!
//! 1. **Two reclaimers.** A and B both observe expired record L0. A renames L0
//!    away first, verifies it, deletes it, and creates L_A. B then renames
//!    whatever is at the path — L_A — verifies the token does not match L0, and
//!    restores it (the path is free because B just moved it). B is refused
//!    `locked` with L_A's holder. No overlapping hold occurs.
//! 2. **Third actor in the restore gap.** If a third process creates a new lock
//!    between B's rename and B's restore, the destination path is occupied and
//!    B cannot restore L_A. B refuses and leaves L_A under
//!    `maintenance.lock.json.stale.<token>` for manual inspection; it is never
//!    deleted because ownership is unknown. A's holder later fails release with
//!    `not_owner` against the third lock, so A learns it lost the lock. This
//!    window is microseconds wide and requires three concurrent maintenance
//!    actors.
//! 3. **Expiry vs. a still-alive holder.** TTL expiry alone is not proof that
//!    the old holder stopped writing. A process that is descheduled past its TTL
//!    can still believe it holds the lease while another process legitimately
//!    reclaims it. The token makes the stale holder's release/extend fail loudly
//!    (`not_owner` / `expired`), but the lock is coordination, **not** a writer
//!    fence: the serving worker must be stopped and its writer resources
//!    released before a maintenance actor mutates the store (NAIOS-001/002).
//!    Extend well before expiry (recommended: at or before 50% of the TTL).
//! 4. **Extend rewrites in place.** Extend re-reads the record, verifies the
//!    token, and truncate-writes the new expiry so the path never disappears.
//!    If the record expires in the microseconds between verification and write
//!    and another actor reclaims it, the write could overwrite the newcomer's
//!    record. Keeping TTLs orders of magnitude larger than the operation and
//!    renewing early makes this unobservable in practice; no new dependency is
//!    introduced just for an atomic replace.
//! 5. **Unreadable records are never stolen.** A partially written, truncated or
//!    unknown-schema file is reported as `lock_unreadable` and left untouched.
//!    Readers treat it as potentially live, so a torn extend cannot open a
//!    takeover window; an operator must remove a genuinely corrupt file.

use std::fs::OpenOptions;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::sync::{Arc, Mutex, MutexGuard};
use std::time::{Instant, SystemTime, UNIX_EPOCH};

use serde::{Deserialize, Serialize};
use serde_json::json;

/// File name of the cross-process maintenance lock inside the runtime root.
pub const MAINTENANCE_LOCK_FILE: &str = "maintenance.lock.json";

/// Schema version of the maintenance lock record.
pub const MAINTENANCE_LOCK_SCHEMA: u32 = 1;

/// Current wall-clock milliseconds since the Unix epoch.
pub fn now_unix_ms() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis() as i64
}

/// Lifecycle state reported by `runtime.health.state`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum RuntimeState {
    /// Runtime resources are being opened; the control surface may not serve yet.
    Starting,
    /// Fully serving.
    Healthy,
    /// Admitting only health/control/status; functional work is winding down.
    Draining,
    /// A maintenance actor holds (or is about to hold) the writer resources.
    Maintenance,
    /// Something is wrong. Wins over `maintenance`.
    Degraded,
}

impl RuntimeState {
    /// Stable wire name (also the serde representation).
    pub const fn as_str(self) -> &'static str {
        match self {
            RuntimeState::Starting => "starting",
            RuntimeState::Healthy => "healthy",
            RuntimeState::Draining => "draining",
            RuntimeState::Maintenance => "maintenance",
            RuntimeState::Degraded => "degraded",
        }
    }
}

impl std::fmt::Display for RuntimeState {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

/// A state transition observed by [`LifecycleController::set_state`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StateTransition {
    /// Controller state before the call.
    pub from: RuntimeState,
    /// New controller state.
    pub to: RuntimeState,
    /// Transition detail (null/absent when unknown).
    pub detail: Option<String>,
    /// Optional ETA for bounded transitions such as draining. Never invented.
    pub eta_ms: Option<u64>,
    /// Wall-clock start of the new state.
    pub since_unix_ms: i64,
}

/// Point-in-time lifecycle view (cheap clone, no I/O).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LifecycleSnapshot {
    /// Current controller state.
    pub state: RuntimeState,
    /// Human-readable detail for the state.
    pub detail: Option<String>,
    /// Most recently recorded error (sticky until overwritten or cleared).
    pub last_error: Option<String>,
    /// Wall-clock start of the current state.
    pub since_unix_ms: i64,
    /// Monotonic age of the current state.
    pub age_ms: u64,
}

#[derive(Debug)]
struct LifecycleInner {
    state: RuntimeState,
    detail: Option<String>,
    last_error: Option<String>,
    since_unix_ms: i64,
    since_instant: Instant,
}

/// Thread-safe, cheaply cloneable lifecycle state holder.
///
/// Clones share one state (the inner value is `Arc<Mutex<_>>`), which lets the
/// runtime hand a handle to best-effort event writers without coupling them to
/// the runtime's lifetime.
#[derive(Debug, Clone)]
pub struct LifecycleController {
    inner: Arc<Mutex<LifecycleInner>>,
}

impl Default for LifecycleController {
    fn default() -> Self {
        Self::new()
    }
}

impl LifecycleController {
    /// Create a controller in the `starting` state.
    pub fn new() -> Self {
        let now = Instant::now();
        Self {
            inner: Arc::new(Mutex::new(LifecycleInner {
                state: RuntimeState::Starting,
                detail: None,
                last_error: None,
                since_unix_ms: now_unix_ms(),
                since_instant: now,
            })),
        }
    }

    fn lock(&self) -> MutexGuard<'_, LifecycleInner> {
        // A panic in a caller must not permanently disable health reporting.
        self.inner.lock().unwrap_or_else(|poisoned| poisoned.into_inner())
    }

    /// Current state.
    pub fn state(&self) -> RuntimeState {
        self.lock().state
    }

    /// Full lifecycle snapshot.
    pub fn snapshot(&self) -> LifecycleSnapshot {
        let guard = self.lock();
        LifecycleSnapshot {
            state: guard.state,
            detail: guard.detail.clone(),
            last_error: guard.last_error.clone(),
            since_unix_ms: guard.since_unix_ms,
            age_ms: guard.since_instant.elapsed().as_millis() as u64,
        }
    }

    /// JSON form: `{state, detail, last_error, since_unix_ms, age_ms}`.
    pub fn snapshot_json(&self) -> serde_json::Value {
        let snapshot = self.snapshot();
        json!({
            "state": snapshot.state.as_str(),
            "detail": snapshot.detail,
            "last_error": snapshot.last_error,
            "since_unix_ms": snapshot.since_unix_ms,
            "age_ms": snapshot.age_ms,
        })
    }

    /// Enter `state`. Returns the transition when the state actually changed.
    ///
    /// Re-entering the current state updates `detail` but keeps the original
    /// `since_unix_ms`/`age_ms` (the state did not restart). `last_error` is
    /// sticky; use [`Self::clear_error`] to drop it.
    pub fn set_state(
        &self,
        state: RuntimeState,
        detail: Option<String>,
    ) -> Option<StateTransition> {
        self.set_state_with_eta(state, detail, None)
    }

    /// [`Self::set_state`] plus an optional, caller-supplied ETA (never invented
    /// by this crate).
    pub fn set_state_with_eta(
        &self,
        state: RuntimeState,
        detail: Option<String>,
        eta_ms: Option<u64>,
    ) -> Option<StateTransition> {
        let detail = detail.filter(|value| !value.trim().is_empty());
        let mut guard = self.lock();
        if guard.state == state {
            guard.detail = detail;
            return None;
        }
        let from = guard.state;
        // Wall clocks can move backwards; make `since` monotonic for consumers.
        let since_unix_ms = now_unix_ms().max(guard.since_unix_ms);
        guard.state = state;
        guard.detail = detail.clone();
        guard.since_unix_ms = since_unix_ms;
        guard.since_instant = Instant::now();
        Some(StateTransition {
            from,
            to: state,
            detail,
            eta_ms,
            since_unix_ms,
        })
    }

    /// Record the most recent error without changing the lifecycle state.
    pub fn record_error(&self, error: &str) {
        self.lock().last_error = Some(error.to_string());
    }

    /// Clear the sticky `last_error`.
    pub fn clear_error(&self) {
        self.lock().last_error = None;
    }
}

/// On-disk maintenance lease record.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MaintenanceLockRecord {
    /// Record schema (currently 1).
    pub schema: u32,
    /// Human/agent identity of the holder (informational, not an authenticator).
    pub owner: String,
    /// Why maintenance is happening (shown in health and refusals).
    pub reason: String,
    /// Fencing token. Returned only to the acquirer; required for release/extend.
    pub token: String,
    /// OS process id that acquired the lease.
    pub pid: u32,
    /// Acquisition wall-clock time (ms since Unix epoch).
    pub acquired_at_unix_ms: i64,
    /// Expiry wall-clock time (ms since Unix epoch).
    pub expires_at_unix_ms: i64,
}

impl MaintenanceLockRecord {
    /// True when the record is schema-valid and has not expired at `now_ms`.
    pub fn is_live(&self, now_ms: i64) -> bool {
        self.schema == MAINTENANCE_LOCK_SCHEMA && now_ms < self.expires_at_unix_ms
    }

    /// Holder JSON used in health/status/refusals. **Never** includes the token.
    pub fn holder_json(&self) -> serde_json::Value {
        json!({
            "owner": self.owner,
            "reason": self.reason,
            "pid": self.pid,
            "acquired_at_unix_ms": self.acquired_at_unix_ms,
            "expires_at_unix_ms": self.expires_at_unix_ms,
        })
    }
}

/// Result of inspecting the lock file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LockInspection {
    /// No lock file.
    Absent,
    /// Schema-valid, unexpired record.
    Live(MaintenanceLockRecord),
    /// Schema-valid record whose TTL has elapsed (reclaimable).
    Expired(MaintenanceLockRecord),
    /// File exists but cannot be trusted (empty, partial, bad schema, I/O error).
    Unreadable {
        /// Human-readable reason.
        error: String,
        /// File mtime when it could be read.
        modified_at_unix_ms: Option<i64>,
    },
}

impl LockInspection {
    /// `runtime.maintenance.status` payload.
    pub fn status_json(&self, now_ms: i64) -> serde_json::Value {
        match self {
            LockInspection::Absent => json!({
                "ok": true,
                "locked": false,
                "expired": false,
                "holder": serde_json::Value::Null,
                "expires_in_ms": serde_json::Value::Null,
            }),
            LockInspection::Live(record) => json!({
                "ok": true,
                "locked": true,
                "expired": false,
                "holder": record.holder_json(),
                "expires_in_ms": (record.expires_at_unix_ms - now_ms).max(0),
            }),
            LockInspection::Expired(record) => json!({
                "ok": true,
                "locked": false,
                "expired": true,
                "holder": record.holder_json(),
                "expires_in_ms": 0,
            }),
            LockInspection::Unreadable { error, .. } => json!({
                "ok": true,
                "locked": serde_json::Value::Null,
                "expired": serde_json::Value::Null,
                "holder": serde_json::Value::Null,
                "expires_in_ms": serde_json::Value::Null,
                "unreadable": true,
                "detail": error,
            }),
        }
    }

    /// `runtime.health.maintenance_lock` payload (nullable).
    ///
    /// An expired record is *not* a held lock. An unreadable file is exposed as
    /// an explicitly unreadable holder because readers must treat it as
    /// potentially live (a torn write must not open a takeover window).
    pub fn health_lock_json(&self) -> Option<serde_json::Value> {
        match self {
            LockInspection::Absent | LockInspection::Expired(_) => None,
            LockInspection::Live(record) => Some(record.holder_json()),
            LockInspection::Unreadable { error, .. } => Some(json!({
                "owner": serde_json::Value::Null,
                "reason": format!("unreadable maintenance lock: {error}"),
                "pid": serde_json::Value::Null,
                "acquired_at_unix_ms": serde_json::Value::Null,
                "expires_at_unix_ms": serde_json::Value::Null,
                "unreadable": true,
            })),
        }
    }

    /// True when a record is present and live.
    pub fn is_live(&self) -> bool {
        matches!(self, LockInspection::Live(_))
    }

    /// True when the file exists but cannot be trusted.
    pub fn is_unreadable(&self) -> bool {
        matches!(self, LockInspection::Unreadable { .. })
    }
}

/// Why a maintenance mutation was refused. Serialized as `{ok:false, reason, holder}`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LockRefusal {
    /// A live foreign lease exists.
    Locked(MaintenanceLockRecord),
    /// No lock file exists.
    NotLocked,
    /// The supplied token is not the current holder's token.
    NotOwner(MaintenanceLockRecord),
    /// The record exists with this token but its TTL elapsed; it must be re-acquired.
    Expired(MaintenanceLockRecord),
    /// The lock file exists but cannot be trusted.
    Unreadable(String),
    /// Repeated reclaim attempts lost every race; retry later.
    Contended,
}

impl LockRefusal {
    /// Stable wire reason.
    pub fn reason(&self) -> &'static str {
        match self {
            LockRefusal::Locked(_) => "locked",
            LockRefusal::NotLocked => "not_locked",
            LockRefusal::NotOwner(_) => "not_owner",
            LockRefusal::Expired(_) => "expired",
            LockRefusal::Unreadable(_) => "lock_unreadable",
            LockRefusal::Contended => "contended",
        }
    }

    fn holder(&self) -> Option<&MaintenanceLockRecord> {
        match self {
            LockRefusal::Locked(record)
            | LockRefusal::NotOwner(record)
            | LockRefusal::Expired(record) => Some(record),
            LockRefusal::NotLocked
            | LockRefusal::Unreadable(_)
            | LockRefusal::Contended => None,
        }
    }

    /// Refusal JSON. The holder's token is never included.
    pub fn to_json(&self) -> serde_json::Value {
        let mut value = json!({
            "ok": false,
            "reason": self.reason(),
            "holder": self.holder().map(MaintenanceLockRecord::holder_json),
        });
        if let LockRefusal::Unreadable(error) = self {
            value["detail"] = json!(error);
        }
        value
    }
}

/// Outcome of `runtime.maintenance.acquire`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AcquireOutcome {
    /// Leases acquired. `token` is the fencing token the caller must keep.
    Acquired {
        /// Fencing token (returned exactly once).
        token: String,
        /// True when an expired lock file was reclaimed on the way.
        reclaimed: bool,
        /// The record now on disk.
        lock: MaintenanceLockRecord,
    },
    /// Refused; no state was changed.
    Refused(LockRefusal),
}

impl AcquireOutcome {
    /// True when this call holds the lease.
    pub fn is_acquired(&self) -> bool {
        matches!(self, AcquireOutcome::Acquired { .. })
    }

    /// NAF response JSON.
    pub fn to_json(&self) -> serde_json::Value {
        match self {
            AcquireOutcome::Acquired {
                token,
                reclaimed,
                lock,
            } => json!({
                "ok": true,
                "token": token,
                "reclaimed": reclaimed,
                "lock": lock.holder_json(),
            }),
            AcquireOutcome::Refused(refusal) => refusal.to_json(),
        }
    }
}

/// Outcome of `runtime.maintenance.release`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ReleaseOutcome {
    /// The caller's lease was removed.
    Released(MaintenanceLockRecord),
    /// Refused; the file (if any) was left untouched.
    Refused(LockRefusal),
}

impl ReleaseOutcome {
    /// NAF response JSON.
    pub fn to_json(&self) -> serde_json::Value {
        match self {
            ReleaseOutcome::Released(record) => json!({
                "ok": true,
                "released": true,
                "lock": record.holder_json(),
            }),
            ReleaseOutcome::Refused(refusal) => refusal.to_json(),
        }
    }
}

/// Outcome of `runtime.maintenance.extend`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ExtendOutcome {
    /// The lease was renewed.
    Extended(MaintenanceLockRecord),
    /// Refused; the file (if any) was left untouched.
    Refused(LockRefusal),
}

impl ExtendOutcome {
    /// NAF response JSON.
    pub fn to_json(&self) -> serde_json::Value {
        match self {
            ExtendOutcome::Extended(record) => json!({
                "ok": true,
                "lock": record.holder_json(),
            }),
            ExtendOutcome::Refused(refusal) => refusal.to_json(),
        }
    }
}

enum Reclaim {
    Reclaimed,
    Vanished,
    StillLocked(MaintenanceLockRecord),
    Unreadable(String),
}

/// Cross-process maintenance lease backed by one JSON file.
#[derive(Debug, Clone)]
pub struct MaintenanceLock {
    path: PathBuf,
}

impl MaintenanceLock {
    /// Lock file at `<root>/maintenance.lock.json`.
    pub fn new(root: impl AsRef<Path>) -> Self {
        Self {
            path: root.as_ref().join(MAINTENANCE_LOCK_FILE),
        }
    }

    /// Exact lock path.
    pub fn path(&self) -> &Path {
        &self.path
    }

    /// Inspect the lock at the current wall clock.
    pub fn inspect(&self) -> LockInspection {
        self.inspect_at(now_unix_ms())
    }

    /// Inspect the lock at an explicit wall clock (tests/diagnostics).
    pub fn inspect_at(&self, now_ms: i64) -> LockInspection {
        match read_record(&self.path) {
            Ok(Some(record)) => {
                if record.schema != MAINTENANCE_LOCK_SCHEMA {
                    LockInspection::Unreadable {
                        error: format!(
                            "unsupported maintenance lock schema {} (expected {})",
                            record.schema, MAINTENANCE_LOCK_SCHEMA
                        ),
                        modified_at_unix_ms: modified_at_unix_ms(&self.path),
                    }
                } else if record.is_live(now_ms) {
                    LockInspection::Live(record)
                } else {
                    LockInspection::Expired(record)
                }
            }
            Ok(None) => LockInspection::Absent,
            Err(error) => LockInspection::Unreadable {
                error,
                modified_at_unix_ms: modified_at_unix_ms(&self.path),
            },
        }
    }

    /// Acquire the lease at the current wall clock.
    pub fn acquire(
        &self,
        owner: &str,
        reason: &str,
        ttl_ms: u64,
    ) -> Result<AcquireOutcome, LockError> {
        self.acquire_at(owner, reason, ttl_ms, now_unix_ms())
    }

    /// Acquire the lease at an explicit wall clock (tests/diagnostics).
    pub fn acquire_at(
        &self,
        owner: &str,
        reason: &str,
        ttl_ms: u64,
        now_ms: i64,
    ) -> Result<AcquireOutcome, LockError> {
        let owner = owner.trim();
        if owner.is_empty() {
            return Err(LockError::InvalidOwner);
        }
        if ttl_ms == 0 {
            return Err(LockError::InvalidTtl);
        }
        if let Some(parent) = self.path.parent() {
            std::fs::create_dir_all(parent)?;
        }

        let token = new_token();
        let expires_at_unix_ms = now_ms.saturating_add(saturating_ttl(ttl_ms));
        let mut reclaimed = false;

        // Bounded: a healthy filesystem converges on the first iteration. The
        // loop only repeats after an expired record is safely reclaimed.
        for _ in 0..5 {
            let record = MaintenanceLockRecord {
                schema: MAINTENANCE_LOCK_SCHEMA,
                owner: owner.to_string(),
                reason: reason.to_string(),
                token: token.clone(),
                pid: std::process::id(),
                acquired_at_unix_ms: now_ms,
                expires_at_unix_ms,
            };
            match self.write_new(&record) {
                Ok(()) => {
                    return Ok(AcquireOutcome::Acquired {
                        token,
                        reclaimed,
                        lock: record,
                    })
                }
                Err(LockError::Io(error))
                    if error.kind() == std::io::ErrorKind::AlreadyExists => {}
                Err(error) => return Err(error),
            }

            match self.inspect_at(now_ms) {
                LockInspection::Live(holder) => {
                    return Ok(AcquireOutcome::Refused(LockRefusal::Locked(holder)))
                }
                LockInspection::Unreadable { error, .. } => {
                    return Ok(AcquireOutcome::Refused(LockRefusal::Unreadable(error)))
                }
                LockInspection::Absent => continue,
                LockInspection::Expired(observed) => match self.reclaim_expired(&observed, now_ms)? {
                    Reclaim::Reclaimed => reclaimed = true,
                    Reclaim::Vanished => {}
                    Reclaim::StillLocked(holder) => {
                        return Ok(AcquireOutcome::Refused(LockRefusal::Locked(holder)))
                    }
                    Reclaim::Unreadable(error) => {
                        return Ok(AcquireOutcome::Refused(LockRefusal::Unreadable(error)))
                    }
                },
            }
        }
        Ok(AcquireOutcome::Refused(LockRefusal::Contended))
    }

    /// Release the lease. Requires the exact token; never deletes a foreign lock.
    pub fn release(&self, token: &str) -> Result<ReleaseOutcome, LockError> {
        let record = match self.inspect() {
            LockInspection::Absent => return Ok(ReleaseOutcome::Refused(LockRefusal::NotLocked)),
            LockInspection::Unreadable { error, .. } => {
                return Ok(ReleaseOutcome::Refused(LockRefusal::Unreadable(error)))
            }
            LockInspection::Live(record) | LockInspection::Expired(record) => record,
        };
        if record.token != token {
            return Ok(ReleaseOutcome::Refused(LockRefusal::NotOwner(record)));
        }

        // Move the exact file aside, re-read it, and only then delete. A stale
        // read can therefore never delete a lock that was replaced meanwhile.
        let staged = self.staging_path("release");
        match std::fs::rename(&self.path, &staged) {
            Ok(()) => {}
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                return Ok(ReleaseOutcome::Refused(LockRefusal::NotLocked))
            }
            Err(error) => return Err(LockError::Io(error)),
        }
        match read_record(&staged) {
            Ok(Some(current)) if current.token == token => {
                let _ = std::fs::remove_file(&staged);
                Ok(ReleaseOutcome::Released(current))
            }
            Ok(Some(current)) => {
                self.restore_or_orphan(&staged, "release");
                Ok(ReleaseOutcome::Refused(LockRefusal::NotOwner(current)))
            }
            Ok(None) => {
                self.restore_or_orphan(&staged, "release");
                Ok(ReleaseOutcome::Refused(LockRefusal::NotLocked))
            }
            Err(error) => {
                self.restore_or_orphan(&staged, "release");
                Ok(ReleaseOutcome::Refused(LockRefusal::Unreadable(error)))
            }
        }
    }

    /// Extend the lease. Requires the exact token; an expired lease cannot renew.
    pub fn extend(&self, token: &str, ttl_ms: u64) -> Result<ExtendOutcome, LockError> {
        self.extend_at(token, ttl_ms, now_unix_ms())
    }

    /// Extend the lease at an explicit wall clock (tests/diagnostics).
    pub fn extend_at(
        &self,
        token: &str,
        ttl_ms: u64,
        now_ms: i64,
    ) -> Result<ExtendOutcome, LockError> {
        if ttl_ms == 0 {
            return Err(LockError::InvalidTtl);
        }
        let record = match self.inspect_at(now_ms) {
            LockInspection::Absent => return Ok(ExtendOutcome::Refused(LockRefusal::NotLocked)),
            LockInspection::Unreadable { error, .. } => {
                return Ok(ExtendOutcome::Refused(LockRefusal::Unreadable(error)))
            }
            LockInspection::Expired(record) => {
                return Ok(ExtendOutcome::Refused(if record.token == token {
                    LockRefusal::Expired(record)
                } else {
                    LockRefusal::NotOwner(record)
                }))
            }
            LockInspection::Live(record) => record,
        };
        if record.token != token {
            return Ok(ExtendOutcome::Refused(LockRefusal::NotOwner(record)));
        }
        let updated = MaintenanceLockRecord {
            expires_at_unix_ms: now_ms.saturating_add(saturating_ttl(ttl_ms)),
            ..record
        };
        match self.rewrite(&updated) {
            Ok(()) => Ok(ExtendOutcome::Extended(updated)),
            Err(LockError::Io(error)) if error.kind() == std::io::ErrorKind::NotFound => {
                Ok(ExtendOutcome::Refused(LockRefusal::NotLocked))
            }
            Err(error) => Err(error),
        }
    }

    fn staging_path(&self, phase: &str) -> PathBuf {
        self.path.with_file_name(format!(
            "{MAINTENANCE_LOCK_FILE}.{phase}.{}.json",
            new_token()
        ))
    }

    fn restore_or_orphan(&self, staged: &Path, phase: &str) {
        match std::fs::rename(staged, &self.path) {
            Ok(()) => {}
            Err(error) => tracing::warn!(
                staged = %staged.display(),
                %error,
                phase,
                "maintenance lock was moved aside but the path was re-taken; leaving the \
                 original record in place for manual inspection (never deleted: ownership unknown)"
            ),
        }
    }

    fn reclaim_expired(
        &self,
        observed: &MaintenanceLockRecord,
        now_ms: i64,
    ) -> Result<Reclaim, LockError> {
        let staged = self.staging_path("stale");
        match std::fs::rename(&self.path, &staged) {
            Ok(()) => {}
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                return Ok(Reclaim::Vanished)
            }
            Err(error) => return Err(LockError::Io(error)),
        }
        match read_record(&staged) {
            // Same record, still expired: we won the reclaim.
            Ok(Some(record))
                if record.token == observed.token && !record.is_live(now_ms) =>
            {
                let _ = std::fs::remove_file(&staged);
                Ok(Reclaim::Reclaimed)
            }
            // The file changed between inspection and rename: restore, never steal.
            Ok(Some(record)) => {
                self.restore_or_orphan(&staged, "reclaim");
                Ok(Reclaim::StillLocked(record))
            }
            Ok(None) => {
                self.restore_or_orphan(&staged, "reclaim");
                Ok(Reclaim::Vanished)
            }
            Err(error) => {
                self.restore_or_orphan(&staged, "reclaim");
                Ok(Reclaim::Unreadable(error))
            }
        }
    }

    /// Atomic create (`create_new`): exactly one contender wins per filesystem.
    fn write_new(&self, record: &MaintenanceLockRecord) -> Result<(), LockError> {
        let bytes = serde_json::to_vec(record)?;
        let mut file = OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&self.path)?;
        if let Err(error) = file.write_all(&bytes).and_then(|()| file.sync_all()) {
            // We created this file; remove the partial artifact we own.
            drop(file);
            let _ = std::fs::remove_file(&self.path);
            return Err(LockError::Io(error));
        }
        Ok(())
    }

    /// In-place renewal: the path never disappears, so mutual exclusion is not
    /// temporarily surrendered. See the module docs for the (microsecond) race.
    fn rewrite(&self, record: &MaintenanceLockRecord) -> Result<(), LockError> {
        let bytes = serde_json::to_vec(record)?;
        let mut file = OpenOptions::new()
            .write(true)
            .truncate(true)
            .open(&self.path)?;
        file.write_all(&bytes)?;
        file.sync_all()?;
        Ok(())
    }
}

/// Maintenance-lock I/O or argument error.
#[derive(Debug, thiserror::Error)]
pub enum LockError {
    /// Filesystem failure.
    #[error("io: {0}")]
    Io(#[from] std::io::Error),
    /// Record encoding failure (should not happen with this fixed schema).
    #[error("encode: {0}")]
    Encode(#[from] serde_json::Error),
    /// Owner is missing/blank.
    #[error("owner must not be empty")]
    InvalidOwner,
    /// TTL must be a positive number of milliseconds.
    #[error("ttl_ms must be greater than zero")]
    InvalidTtl,
}

fn read_record(path: &Path) -> Result<Option<MaintenanceLockRecord>, String> {
    match std::fs::read(path) {
        Ok(bytes) => {
            if bytes.is_empty() {
                return Err(format!(
                    "{} is empty (lock writer in progress or crashed mid-write)",
                    path.display()
                ));
            }
            serde_json::from_slice::<MaintenanceLockRecord>(&bytes)
                .map(Some)
                .map_err(|error| format!("{} is not a valid lock record: {error}", path.display()))
        }
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(format!("{} could not be read: {error}", path.display())),
    }
}

fn modified_at_unix_ms(path: &Path) -> Option<i64> {
    std::fs::metadata(path)
        .and_then(|metadata| metadata.modified())
        .ok()
        .and_then(|time| time.duration_since(UNIX_EPOCH).ok())
        .map(|duration| duration.as_millis() as i64)
}

fn new_token() -> String {
    // Two UUIDv7s: 148 random bits, time-ordered but not guessable from a pid.
    format!(
        "{}{}",
        uuid::Uuid::now_v7().simple(),
        uuid::Uuid::now_v7().simple()
    )
}

fn saturating_ttl(ttl_ms: u64) -> i64 {
    i64::try_from(ttl_ms).unwrap_or(i64::MAX)
}

